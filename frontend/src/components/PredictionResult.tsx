import type { PredictionResult as Prediction } from '../types/wine'

interface PredictionResultProps {
  prediction: Prediction | null
  error: string | null
}

export function PredictionResult({ prediction, error }: PredictionResultProps) {
  const quality = prediction?.predicted_quality
  const progress = quality === undefined ? 0 : Math.max(0, Math.min(100, quality * 10))

  return (
    <section className="panel result-panel" aria-live="polite">
      <div className="result-header">
        <h2>Prediction result</h2>
        <span className="result-tag">MODEL OUTPUT</span>
      </div>

      <div className="result-body">
        {error ? (
          <div className="error-message" role="alert">
            <svg viewBox="0 0 20 20" aria-hidden="true"><path d="M10 2.5 18 17H2L10 2.5Z" /><path d="M10 7v4.5M10 14.5v.1" /></svg>
            <span>{error}</span>
          </div>
        ) : quality === undefined ? (
          <div className="result-empty">
            <span className="empty-glyph" aria-hidden="true">
              <svg viewBox="0 0 24 24"><path d="M12 3v18M5 7c3.8 0 7 2.1 7 5s-3.2 5-7 5M19 7c-3.8 0-7 2.1-7 5s3.2 5 7 5" /></svg>
            </span>
            <strong>Ready when you are</strong>
            <p>Submit the wine measurements to see its estimated quality score.</p>
          </div>
        ) : (
          <div className="quality-result">
            <div className="quality-number">{quality.toFixed(2)}</div>
            <div className="quality-caption">Estimated quality score</div>
            <div className="quality-track" aria-label={`Quality score ${quality.toFixed(2)} out of 10`}>
              <div className="quality-fill" style={{ width: `${progress}%` }} />
            </div>
            <div className="quality-scale"><span>0</span><span>5</span><span>10</span></div>
            <div className="quality-note"><strong>Continuous estimate.</strong> The model returns a regression score; it is not rounded to a whole number.</div>
          </div>
        )}
      </div>

      <div className="result-footnote">
        <span className="result-footnote-dot" />
        Prediction generated by the trained Random Forest model
      </div>
    </section>
  )
}
